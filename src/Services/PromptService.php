    /**
     * System prompt for evaluating the nutritional and variety balance of a weekly meal plan.
     */
    public static function getEvaluationSystemPrompt(): string
    {
        return <<<PROMPT
You are an expert nutritional advisor and culinary planner for Plate Plan.
Your job is to thoroughly evaluate the user's weekly meal schedule and provide an insightful, structured review.

Evaluation Criteria:
1. **Caloric & Macro Balance**: Protein adequacy, healthy complex carbs, dietary fats, and dietary fiber.
2. **Nutritional Variety & Micronutrients**: Diverse vegetables, greens, fruits, lean meats/fish/legumes, avoiding repetitive nutrient gaps.
3. **Daily Coverage**: Gaps or days missing breakfast, lunch, or dinner.
4. **Actionable Recommendations**: 2 to 4 concrete suggestions (e.g., adding leafy greens on Thursday, swapping a processed meal for whole foods).
5. **Overall Score**: A score out of 100 with a short summary title (e.g., "85/100 · Well Balanced & Nutrient Dense").

Formatting:
- Structure your response with clean Markdown:
  - 🏆 **Overall Score & Summary**
  - 🥗 **Nutritional Strengths**
  - ⚠️ **Areas for Improvement & Missing Gaps**
  - 💡 **Actionable Tips for this Week**
- Keep the language engaging, constructive, and practical.
- Always end with the mandatory disclaimer:
  "*Disclaimer: This evaluation is generated by AI and may contain errors. It is not intended as medical or clinical nutrition advice. Please consult a qualified nutritionist or physician for personalized healthcare plans.*"
PROMPT;
    }

    /**
     * Formats the user's current weekly plan into a prompt payload for evaluation.
     */
    public static function formatEvaluationPrompt(array $weeklyPlan, array $allMeals): string
    {
        $days = [
            1 => 'Monday',
            2 => 'Tuesday',
            3 => 'Wednesday',
            4 => 'Thursday',
            5 => 'Friday',
            6 => 'Saturday',
            7 => 'Sunday',
        ];

        // Map meals by ID for fast ingredient lookup
        $mealMap = [];
        foreach ($allMeals as $meal) {
            $mealMap[$meal['id']] = $meal;
        }

        // Group weekly plan by day
        $planByDay = [];
        foreach ($weeklyPlan as $item) {
            $dayNum = (int)$item['day_of_week'];
            $planByDay[$dayNum][] = $item;
        }

        $lines = ["Here is the current weekly meal schedule to evaluate:\n"];

        foreach ($days as $dayNum => $dayName) {
            $lines[] = "### {$dayName}:";
            if (empty($planByDay[$dayNum])) {
                $lines[] = "  * No meals planned.";
                continue;
            }

            foreach ($planByDay[$dayNum] as $slot) {
                $mId = $slot['meal_id'];
                $mName = $slot['meal_name'] ?? ($mealMap[$mId]['name'] ?? 'Unknown Meal');
                $mType = ucfirst($slot['meal_type']);
                $ings = [];
                if (isset($mealMap[$mId]['ingredients'])) {
                    foreach ($mealMap[$mId]['ingredients'] as $ing) {
                        $ings[] = $ing['name'] . ' (' . ($ing['quantity'] ?: '1 portion') . ')';
                    }
                }
                $ingStr = !empty($ings) ? ' [' . implode(', ', $ings) . ']' : '';
                $lines[] = "  * **{$mType}**: {$mName}{$ingStr}";
            }
        }

        $lines[] = "\nPlease evaluate this weekly plan according to your criteria.";
        return implode("\n", $lines);
    }

    /**
     * Standard user-facing AI disclaimer notice.
     */
    public static function getNoticeDisclaimer(): string
    {
        return 'AI is generating this evaluation. AI can make mistakes — always consult a healthcare or nutrition professional for specific health or dietary needs.';
    }
}
